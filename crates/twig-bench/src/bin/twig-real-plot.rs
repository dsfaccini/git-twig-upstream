//! Render measured image cohorts from raw JSON; tables go to stdout, charts to SVG.
use anyhow::{Context, Result, ensure};
use serde_json::Value;
use std::{collections::BTreeSet, env, fs, path::PathBuf};

fn main() -> Result<()> {
    let path = PathBuf::from(
        env::args_os()
            .nth(1)
            .context("usage: twig-real-plot target/real-results/run.json")?,
    );
    let run: Value = serde_json::from_slice(&fs::read(&path)?)?;
    ensure!(
        (run["suite"] == "real-apfs-cohort"
            && (run["schemaVersion"] == 1 || run["schemaVersion"] == 2))
            || (run["suite"] == "real-image-cohort"
                && matches!(run["schemaVersion"].as_u64(), Some(3 | 4))),
        "unsupported suite/schema"
    );
    let cohorts = run["cohorts"].as_array().context("missing cohorts")?;
    let mut table = String::from(
        "<!-- Generated by twig-real-plot from adjacent JSON; do not edit. -->\n\nCreate percentiles include every attempt, including failures. Space is isolated filesystem allocated-space growth after first status, including metadata and staging. Host-filesystem runs deliberately report allocation as unmeasured. Ranges show observed allocator variation, not statistical confidence intervals.\n\n| repository | backend | repeat | success | create wall s | p50 ms | p95 ms | p99 ms | max ms | first status p50 ms | allocation MiB | after one-byte writes MiB | all space snapshots stable |\n|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|\n",
    );
    let repository_count = run["repositories"]
        .as_array()
        .map(Vec::len)
        .unwrap_or_else(|| {
            cohorts
                .iter()
                .filter_map(|c| c["repository"].as_str())
                .collect::<BTreeSet<_>>()
                .len()
        });
    let planned_cohorts = repository_count as u64
        * if run["selectedBackend"].is_string() {
            1
        } else {
            2
        }
        * run["repeats"].as_u64().context("repeats")?;
    table.insert_str(0, &format!("Filesystem: **{}**. Cohort records: **{}/{}** planned for the recorded/observed repositories. Missing cohorts are unmeasured, not zero. Check any adjacent stop-event file for a budget stop.\n\n", run["filesystem"].as_str().unwrap_or("isolated-image"), cohorts.len(), planned_cohorts));
    for cohort in cohorts {
        let operations = cohort["operations"].as_array().context("operations")?;
        let create: Vec<_> = operations
            .iter()
            .filter_map(|op| op["createMs"].as_f64())
            .collect();
        let status: Vec<_> = operations
            .iter()
            .filter_map(|op| op["firstStatusMs"].as_f64())
            .collect();
        let stable = if cohort["before"].is_null() {
            "unmeasured".into()
        } else {
            ["before", "afterCreate", "afterStatus", "afterPrivateWrites"]
                .iter()
                .all(|key| cohort[key]["stable"] == true)
                .to_string()
        };
        table.push_str(&format!("| {} | {} | {} | {}/{} | {:.3} | {:.2} | {:.2} | {:.2} | {:.2} | {:.2} | {} | {} | {} |\n", cohort["repository"].as_str().context("repository")?, cohort["backend"].as_str().context("backend")?, cohort["repeat"].as_u64().context("repeat")? + 1, cohort["succeeded"], operations.len(), number(cohort, "createWallMs")? / 1000.0, percentile(&create, 0.5), percentile(&create, 0.95), percentile(&create, 0.99), percentile(&create, 1.0), percentile(&status, 0.5), delta_mib(cohort, "before", "afterStatus"), delta_mib(cohort, "afterStatus", "afterPrivateWrites"), stable));
    }
    print!("{table}");
    let labels: BTreeSet<_> = cohorts
        .iter()
        .filter_map(|c| c["repository"].as_str())
        .collect();
    for label in labels {
        let rows: Vec<_> = cohorts
            .iter()
            .filter(|c| c["repository"] == label)
            .collect();
        let height = 125 + rows.len() * 74;
        let max_time = rows
            .iter()
            .filter_map(|c| c["createWallMs"].as_f64())
            .fold(1.0, f64::max)
            * 1.1;
        let max_space = rows
            .iter()
            .filter_map(|c| c["growthAfterStatusBytes"].as_f64())
            .fold(1.0, f64::max)
            * 1.1;
        let mut svg = format!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"1100\" height=\"{height}\"><rect width=\"100%\" height=\"100%\" fill=\"#111827\"/><g fill=\"#e5e7eb\" font-family=\"system-ui,sans-serif\"><text x=\"20\" y=\"30\" font-size=\"20\">{} · {} worktrees · concurrency {} · {}</text><text x=\"200\" y=\"61\" font-size=\"14\">creation wall time (seconds)</text><text x=\"650\" y=\"61\" font-size=\"14\">allocated filesystem growth (MiB)</text>",
            escape(label),
            run.get("worktreesPerCohort").unwrap_or(&run["concurrency"]),
            run["concurrency"],
            escape(run["filesystem"].as_str().context("filesystem")?)
        );
        for (index, cohort) in rows.iter().enumerate() {
            let y = 82 + index * 74;
            let backend = cohort["backend"].as_str().context("backend")?;
            let color = if backend == "git" {
                "#94a3b8"
            } else {
                "#34d399"
            };
            let time = number(cohort, "createWallMs")?;
            let space = cohort["growthAfterStatusBytes"].as_f64();
            svg.push_str(&format!(
                "<text x=\"20\" y=\"{}\" font-size=\"13\">{} · run {} · {} ok</text>",
                y + 19,
                escape(backend),
                cohort["repeat"].as_u64().context("repeat")? + 1,
                cohort["succeeded"]
            ));
            let mut bars = vec![(
                200.0,
                time / max_time * 340.0,
                format!("{:.3} s", time / 1000.0),
            )];
            if let Some(space) = space {
                bars.push((
                    650.0,
                    space.max(0.0) / max_space * 340.0,
                    format!("{:.3} MiB", space / 1048576.0),
                ));
            } else {
                svg.push_str(&format!("<text x=\"650\" y=\"{}\" font-size=\"12\">unmeasured on shared host filesystem</text>", y + 19));
            }
            for (x, width, text) in bars {
                svg.push_str(&format!("<rect x=\"{x}\" y=\"{y}\" width=\"{width:.2}\" height=\"28\" rx=\"3\" fill=\"{color}\"/><text x=\"{:.2}\" y=\"{}\" font-size=\"12\">{text}</text>", x + width + 6.0, y + 19));
            }
            if cohort["failed"].as_u64().context("failed")? > 0 {
                svg.push_str(&format!("<text x=\"200\" y=\"{}\" fill=\"#f87171\" font-size=\"12\">{} failures — not a complete successful cohort</text>", y + 47, cohort["failed"]));
            }
        }
        svg.push_str("</g></svg>\n");
        let stem = path
            .file_stem()
            .context("missing file stem")?
            .to_string_lossy();
        fs::write(path.with_file_name(format!("{stem}-{label}.svg")), svg)?;
    }
    Ok(())
}
fn allocation_bounds(snapshot: &Value) -> Option<(f64, f64)> {
    let point = snapshot["allocatedBytes"].as_f64()?;
    Some(
        snapshot["observedAllocatedBytes"]
            .as_array()?
            .iter()
            .filter_map(Value::as_f64)
            .fold((point, point), |(low, high), value| {
                (low.min(value), high.max(value))
            }),
    )
}
fn delta_mib(cohort: &Value, before: &str, after: &str) -> String {
    let Some(((before_low, before_high), (after_low, after_high))) =
        allocation_bounds(&cohort[before]).zip(allocation_bounds(&cohort[after]))
    else {
        return "unmeasured".into();
    };
    let low = (after_low - before_high) / 1048576.0;
    let high = (after_high - before_low) / 1048576.0;
    if (high - low).abs() < 0.0001 {
        format!("{low:.3}")
    } else {
        format!("{low:.3}–{high:.3}")
    }
}
fn number(value: &Value, key: &str) -> Result<f64> {
    value[key]
        .as_f64()
        .with_context(|| format!("missing {key}"))
}
fn escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
fn percentile(values: &[f64], fraction: f64) -> f64 {
    if values.is_empty() {
        return 0.0;
    }
    let mut sorted = values.to_vec();
    sorted.sort_by(f64::total_cmp);
    sorted[((sorted.len() as f64 * fraction).ceil() as usize)
        .saturating_sub(1)
        .min(sorted.len() - 1)]
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn reports_allocator_observation_ranges() {
        let cohort = serde_json::json!({
            "before": {"allocatedBytes": 1048576, "observedAllocatedBytes": [1048576, 2097152]},
            "afterStatus": {"allocatedBytes": 4194304, "observedAllocatedBytes": [3145728, 4194304]}
        });
        assert_eq!(delta_mib(&cohort, "before", "afterStatus"), "1.000–3.000");
        assert_eq!(
            delta_mib(&Value::Null, "before", "afterStatus"),
            "unmeasured"
        );
    }
}
